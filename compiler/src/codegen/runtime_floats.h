/*
 * Floats as text, the same on every system. A float is written as the
 * shortest decimal that reads back as the same float, the closest one when
 * several are as short, and of two as close the one whose last digit is
 * even. No C library function decides the digits, so no system can write
 * them differently. The compiler adds this part of the runtime to a program
 * that writes a float.
 *
 * The digits come from the Schubfach algorithm of Raffaello Giulietti ("The
 * Schubfach way to render doubles", 2020), which finds them with a few
 * 64-bit multiplications by a 126-bit approximation of a power of ten.
 */

