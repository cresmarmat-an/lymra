/*!
 * Code generation: turns a checked program into one C file.
 *
 * The file holds, in order: the runtime, one static string for each place
 * that can stop the program at run time, the top-level constants, a prototype
 * for every function so calls do not depend on order, the functions, and the
 * C `main` that calls the Lymra one.
 *
 * Every integer operation the optimizer could not prove safe goes through a
 * runtime function that traps on overflow and on division by zero, as spec
 * section 4.2 requires in every build mode. Comparisons and logic cannot
 * fail, so they stay plain C.
 */

mod c_syntax;
mod expressions;
mod statements;

use crate::diagnostics::render_location;
use crate::ir::{Function, Program, Statement};
use crate::source::{SourceFile, Span};

const RUNTIME: &str = include_str!("runtime.h");
const INDENT: &str = "    ";

/// Generates the C source for a checked program.
pub fn generate(program: &Program<'_>, source: &SourceFile) -> String {
    let mut generator = Generator {
        program,
        source,
        sites: Vec::new(),
        helpers: 0,
    };
    let functions: Vec<String> = program
        .functions
        .iter()
        .map(|function| generator.function(function))
        .collect();

    let mut output = String::new();
    let file_name = source.name().replace("*/", "* /");
    output.push_str(&format!(
        "/* Generated by the Lymra compiler from {file_name}. Edit the Lymra source, not this file. */\n\n"
    ));
    output.push_str(RUNTIME);
    section(
        &mut output,
        "Places that can stop the program",
        &generator.sites,
    );
    section(&mut output, "Constants", &constants(program));
    section(&mut output, "Prototypes", &prototypes(program));
    section(&mut output, "Functions", &[functions.join("\n\n")]);
    if let Some(main) = program.main.and_then(|id| program.functions.get(id)) {
        let entry_point = format!(
            "int main(void) {{\n{INDENT}lymra_start();\n{INDENT}{}();\n{INDENT}return lymra_finish();\n}}",
            c_syntax::function_name(main.name)
        );
        section(&mut output, "Entry point", &[entry_point]);
    }
    output
}

fn section(output: &mut String, title: &str, parts: &[String]) {
    if parts.iter().all(String::is_empty) {
        return;
    }
    output.push_str(&format!("\n/* {title} */\n\n"));
    for part in parts {
        output.push_str(part);
        output.push('\n');
    }
}

fn constants(program: &Program<'_>) -> Vec<String> {
    program
        .constants
        .iter()
        // A constant named `_` can never be read, so it needs no storage.
        .filter(|constant| constant.name != "_")
        .map(|constant| {
            format!(
                "LYMRA_UNUSED static const {} {} = {};",
                c_syntax::type_name(constant.value.ty()),
                c_syntax::constant_name(constant.name),
                c_syntax::static_initializer(&constant.value)
            )
        })
        .collect()
}

fn prototypes(program: &Program<'_>) -> Vec<String> {
    program
        .functions
        .iter()
        .map(|function| format!("{};", signature(function)))
        .collect()
}

/// The C declaration of a function, without a body or a semicolon.
fn signature(function: &Function<'_>) -> String {
    let return_type = function.return_type.map_or("void", c_syntax::type_name);
    let parameters: Vec<String> = function
        .parameters
        .iter()
        .enumerate()
        .map(|(position, &id)| {
            let local = &function.locals[id];
            let name = if local.name == "_" {
                format!("unused_parameter_{position}")
            } else {
                c_syntax::local_name(local.name)
            };
            let ty = c_syntax::type_name(local.ty);
            if local.by_reference {
                format!("{ty} *{name}")
            } else {
                format!("const {ty} {name}")
            }
        })
        .collect();
    let parameters = if parameters.is_empty() {
        "void".to_owned()
    } else {
        parameters.join(", ")
    };
    format!(
        "LYMRA_UNUSED static {return_type} {}({parameters})",
        c_syntax::function_name(function.name)
    )
}

/// Collects indented lines of C.
struct Writer {
    text: String,
    depth: usize,
}

impl Writer {
    /// An empty writer whose lines start `depth` levels in.
    const fn at(depth: usize) -> Self {
        Self {
            text: String::new(),
            depth,
        }
    }

    fn line(&mut self, line: &str) {
        self.text.push_str(&INDENT.repeat(self.depth));
        self.text.push_str(line);
        self.text.push('\n');
    }

    fn is_empty(&self) -> bool {
        self.text.is_empty()
    }

    /// Adds the lines of `other`, which keep their own indentation.
    fn append(&mut self, other: Writer) {
        self.text.push_str(&other.text);
    }
}

struct Generator<'program, 'src> {
    program: &'program Program<'src>,
    source: &'program SourceFile,
    /// One `static const char` definition per place that can stop the program, in order of use.
    sites: Vec<String>,
    /// Counts helper variables, so each has a name of its own.
    helpers: usize,
}

impl Generator<'_, '_> {
    fn function(&mut self, function: &Function<'_>) -> String {
        let mut writer = Writer {
            text: format!("{} {{\n", signature(function)),
            depth: 1,
        };
        self.block_contents(function, &function.body, &mut writer);
        let ends_with_return =
            matches!(function.body.statements.last(), Some(Statement::Return(_)));
        if function.return_type.is_some() && !ends_with_return {
            // The checker proved that every path returns, so control never gets here.
            writer.line("LYMRA_UNREACHABLE();");
        }
        writer.text.push('}');
        writer.text
    }

    /// Registers a place that can stop the program and returns the name of its description.
    fn site(&mut self, span: Span) -> String {
        let name = format!("lymra_site_{}", self.sites.len());
        let description = render_location(span, self.source);
        self.sites.push(format!(
            "static const char {name}[] = {};",
            c_syntax::string_literal(&description)
        ));
        name
    }

    /// A new name for a helper variable, made of `role` and a number no other helper has.
    fn helper(&mut self, role: &str) -> String {
        let name = format!("{role}_{}", self.helpers);
        self.helpers += 1;
        name
    }
}

/// How a local is read or assigned: through the pointer when it is a `variable` parameter.
fn local_access(function: &Function<'_>, id: usize) -> String {
    let local = &function.locals[id];
    let name = c_syntax::local_name(local.name);
    if local.by_reference {
        format!("(*{name})")
    } else {
        name
    }
}
