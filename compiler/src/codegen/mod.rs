const RUNTIME: &str = include_str!("runtime.h");
/// The part of the runtime that writes floats as text, added to a program that does.
const RUNTIME_FLOATS: &str = include_str!("runtime_floats.h");
const INDENT: &str = "    ";

/// The largest frame the runtime is told about. A frame anywhere near it cannot run, so a larger one changes nothing.
const FRAME_CEILING: u64 = 1 << 30;

/// Generates the C source for a checked program.
pub fn generate(program: &Program<'_>, source: &SourceFile) -> String {
    let mut generator = Generator {
        program,
        source,
        sites: Vec::new(),
        helpers: 0,
        types: CTypes::default(),
        frame: 0,
        largest_frame: 0,
        writes_floats: false,
        data_stacks: 0,
        scopes: Vec::new(),
        pending: Vec::new(),
        text_regions: HashMap::new(),
        return_stack: None,
    };
    let functions: Vec<String> = program
        .functions
        .iter()
        .map(|function| generator.function(function))
        .collect();
    let prototypes: Vec<String> = program
        .functions
        .iter()
        .map(|function| format!("{};", generator.signature(function)))
        .collect();
    let constants = generator.constants();
    let entry_point = program
        .main
        .and_then(|id| program.functions.get(id))
        .map(|main| generator.entry_point(main));

    let mut output = String::new();
    let file_name = source.name().replace("*/", "* /");
    output.push_str(&format!(
        "/* Generated by the Lymra compiler from {file_name}. Edit the Lymra source, not this file. */\n\n"
    ));
    output.push_str(&format!(
        "#define LYMRA_LARGEST_FRAME ((size_t){})\n\n",
        generator.largest_frame.min(FRAME_CEILING)
    ));
    if generator.writes_floats || generator.types.uses_floats {
        output.push_str("#define LYMRA_USES_FLOATS 1\n\n");
    }
    // The runtime declares the data stacks along with the type a list's struct names, so a program that names a list type has one at least.
    let data_stacks = if generator.types.uses_data_stacks {
        generator.data_stacks.max(1)
    } else {
        generator.data_stacks
    };
    if data_stacks > 0 {
        output.push_str(&format!("#define LYMRA_DATA_STACKS {data_stacks}\n\n"));
    }
    output.push_str(RUNTIME);
    if generator.writes_floats {
        output.push('\n');
        output.push_str(RUNTIME_FLOATS);
    }
    section(&mut output, "Types", generator.types.definitions());
    section(
        &mut output,
        "Places that can stop the program",
        &generator.sites,
    );
    section(&mut output, "Constants", &constants);
    section(&mut output, "Prototypes", &prototypes);
    section(&mut output, "Functions", &[functions.join("\n\n")]);
    if let Some(entry_point) = entry_point {
        section(&mut output, "Entry point", &[entry_point]);
    }
    output
}

fn section(output: &mut String, title: &str, parts: &[String]) {
    if parts.iter().all(String::is_empty) {
        return;
    }
    output.push_str(&format!("\n/* {title} */\n\n"));
    for part in parts {
        output.push_str(part);
        output.push('\n');
    }
}

/// Collects indented lines of C.
struct Writer {
    text: String,
    depth: usize,
}

impl Writer {
    /// An empty writer whose lines start `depth` levels in.
    const fn at(depth: usize) -> Self {
        Self {
            text: String::new(),
            depth,
        }
    }

    fn line(&mut self, line: &str) {
        self.text.push_str(&INDENT.repeat(self.depth));
        self.text.push_str(line);
        self.text.push('\n');
    }

    fn is_empty(&self) -> bool {
        self.text.is_empty()
    }

    /// Adds the lines of `other`, which keep their own indentation.
    fn append(&mut self, other: Writer) {
        self.text.push_str(&other.text);
    }
}

struct Generator<'program, 'src> {
    program: &'program Program<'src>,
    source: &'program SourceFile,
    /// One `static const char` definition per place that can stop the program, in order of use.
    sites: Vec<String>,
    /// Counts helper variables, so each has a name of its own.
    helpers: usize,
    types: CTypes,
    /// The bytes of arrays and declared types the function being generated keeps in its frame.
    frame: u64,
    /**
     * An upper bound on the frame of every function so far: twice its arrays,
     * since the C compiler may copy one through a hidden temporary.
     */
    largest_frame: u64,
    /// Whether the program writes a float as text, which needs the runtime's float printer.
    writes_floats: bool,
    /// The data stacks handed out so far, numbered from 0.
    data_stacks: usize,
    /// The C blocks open in the function being generated, innermost last.
    scopes: Vec<Scope>,
    /// The lists and text the statement being generated computed without a binding, which it frees once it is done.
    pending: Vec<Release>,
    /// The data stack and the start of the text of each local that holds text, in the function being generated.
    text_regions: HashMap<LocalId, Region>,
    /// The data stack the function's `return` copies its text onto before it frees its own, once it needs one.
    return_stack: Option<usize>,
}

/// Where a value keeps its text: a data stack, and where the value's text starts on it, both as C.
#[derive(Clone, Debug)]
struct Region {
    stack: String,
    start: String,
}

/// What a value keeps on data stacks, beyond its C struct.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Storage {
    /// Nothing: all of it is in its C struct.
    None,
    /// Its elements: a list, a stack or a pool whose values hold no text.
    Elements,
    /// The bytes of the text it holds: a `string`, or a type, an array or a choice that holds one.
    Text,
    /// Its elements and the text they hold, each on a data stack of its own.
    ElementsAndText,
}

impl Storage {
    fn of(ty: &Type) -> Storage {
        // A view keeps nothing: it shows what something else keeps.
        if ty.as_view().is_some() {
            return Storage::None;
        }
        match (ty.is_growable(), ty.holds_text()) {
            (false, false) => Storage::None,
            (true, false) => Storage::Elements,
            (false, true) => Storage::Text,
            (true, true) => Storage::ElementsAndText,
        }
    }
}

/**
 * Something to free: the elements of a list, or text, and its data stack.
 * Freeing it moves the top of the stack down to where it starts. Nothing of
 * the same call lies above it then, and a list from an earlier call that
 * grew while this one was being built lies below it, so that one keeps its
 * elements.
 */
#[derive(Clone, Debug)]
struct Release {
    stack: usize,
    /// Where it starts, which becomes the top of its stack, as C.
    start: String,
}

impl Release {
    /// The elements of the list `list`.
    fn elements(stack: usize, list: &str) -> Self {
        Self {
            stack,
            start: format!("(char *){list}.elements"),
        }
    }
}

/// An open C block and the lists it frees when control leaves it.
#[derive(Debug, Default)]
struct Scope {
    releases: Vec<Release>,
    /// Whether the block is a loop's body, which `break` and `continue` leave.
    loop_body: bool,
}

impl Generator<'_, '_> {
    /**
     * The C `main`. It starts the runtime, gives the program's `main` the
     * command-line arguments if it takes them, and ends with the exit status
     * `main` returns, 0 when it returns none. A `main` that can fail gives a
     * result, and on a `Failure` the runtime writes its text and ends with
     * status 1 (spec 8). The arguments lie on a data stack of their own,
     * freed once `main` is done.
     */
    fn entry_point(&mut self, main: &Function<'_>) -> String {
        let mut lines = vec!["lymra_start();".to_owned()];
        let mut call_arguments: Vec<String> = match &main.return_type {
            Some(returned) => destination_names(Storage::of(returned))
                .iter()
                .map(|_| data_stack(self.new_data_stack()))
                .collect(),
            None => Vec::new(),
        };
        let mut header = "int main(void)";
        let mut free_arguments = None;
        if let Some(&parameter) = main.parameters.first() {
            header = "int main(int argc, char **argv)";
            let stack = data_stack(self.new_data_stack());
            let view = self.types.name(&main.locals[parameter].ty);
            lines.push(format!("char *const arguments_start = ({stack})->top;"));
            lines.push("int64_t argument_count = 0;".to_owned());
            lines.push(format!(
                "const lymra_string *const argument_list = lymra_arguments(argc, argv, {stack}, &argument_count);"
            ));
            lines.push(format!(
                "const {view} arguments = {{ argument_list, argument_count }};"
            ));
            call_arguments.push("arguments".to_owned());
            free_arguments = Some(format!(
                "lymra_data_stack_release({stack}, arguments_start);"
            ));
        }
        let call = format!(
            "{}({})",
            c_syntax::function_name(main.name),
            call_arguments.join(", ")
        );
        let status = match &main.return_type {
            None => {
                lines.push(format!("{call};"));
                "0".to_owned()
            }
            Some(returned) => {
                let c_type = self.types.name(returned);
                lines.push(format!("const {c_type} result = {call};"));
                match returned.as_result() {
                    Some(result) => {
                        lines.push(format!(
                            "if (result.{} == {FAILURE_VARIANT}) {{",
                            c_syntax::TAG
                        ));
                        lines.push(format!(
                            "{INDENT}lymra_main_failed(result.{}.{}.{});",
                            c_syntax::VARIANTS,
                            c_syntax::variant_name(FAILURE_VARIANT),
                            c_syntax::field_name(0)
                        ));
                        lines.push("}".to_owned());
                        match result.success_type() {
                            Some(_) => format!(
                                "result.{}.{}.{}",
                                c_syntax::VARIANTS,
                                c_syntax::variant_name(SUCCESS_VARIANT),
                                c_syntax::field_name(0)
                            ),
                            None => "0".to_owned(),
                        }
                    }
                    None => "result".to_owned(),
                }
            }
        };
        lines.extend(free_arguments);
        lines.push(format!("return lymra_finish({status});"));
        let body: Vec<String> = lines.iter().map(|line| format!("{INDENT}{line}")).collect();
        format!("{header} {{\n{}\n}}", body.join("\n"))
    }

    fn function(&mut self, function: &Function<'_>) -> String {
        self.scopes.clear();
        self.pending.clear();
        self.text_regions.clear();
        self.return_stack = None;
        /*
         * A function that returns only text the program keeps leaves where
         * its result goes unused, and one that gives a `variable` parameter
         * no new text leaves where that text goes unused.
         */
        let mut maybe_unused: Vec<String> = function
            .return_type
            .as_ref()
            .map_or(Vec::new(), |ty| destination_names(Storage::of(ty)))
            .into_iter()
            .map(str::to_owned)
            .collect();
        for &parameter in &function.parameters {
            let local = &function.locals[parameter];
            if local.by_reference && Storage::of(&local.ty) == Storage::Text {
                let name = c_syntax::local_name(local.name);
                let region = Region {
                    stack: c_syntax::text_stack_name(&name),
                    start: c_syntax::text_start_name(&name),
                };
                maybe_unused.push(region.stack.clone());
                maybe_unused.push(region.start.clone());
                self.text_regions.insert(parameter, region);
            }
        }
        self.frame = (0..function.locals.len())
            .filter(|&id| !is_pointer(function, id))
            .map(|id| compound_bytes(&function.locals[id].ty))
            .fold(0, u64::saturating_add);
        let mut writer = Writer {
            text: format!("{} {{\n", self.signature(function)),
            depth: 1,
        };
        for name in &maybe_unused {
            writer.line(&format!("(void){name};"));
        }
        self.block_contents(function, &function.body, &mut writer);
        self.largest_frame = self.largest_frame.max(self.frame.saturating_mul(2));
        let ends_with_return =
            matches!(function.body.statements.last(), Some(Statement::Return(_)));
        if function.return_type.is_some() && !ends_with_return {
            // The checker proved that every path returns, so control never gets here.
            writer.line("LYMRA_UNREACHABLE();");
        }
        writer.text.push('}');
        writer.text
    }

    /**
     * The C declaration of a function, without a body or a semicolon. A
     * `variable` parameter is a pointer to the caller's binding, and an array
     * parameter a pointer to a value the call cannot change, so no call
     * copies an array. A function that returns a list or text first takes
     * the data stacks where its caller wants it. A `variable` parameter that
     * holds text comes with the data stack of that text and where it starts,
     * so the function can give the caller's binding new text.
     */
    fn signature(&mut self, function: &Function<'_>) -> String {
        let return_type = match &function.return_type {
            Some(ty) => self.types.name(ty),
            None => "void".to_owned(),
        };
        let destinations = function
            .return_type
            .as_ref()
            .map_or(Vec::new(), |ty| destination_names(Storage::of(ty)))
            .into_iter()
            .map(|name| format!("lymra_data_stack *{name}"));
        let mut parameters: Vec<String> = destinations.collect();
        for (position, &id) in function.parameters.iter().enumerate() {
            let local = &function.locals[id];
            let name = if local.name == "_" {
                format!("unused_parameter_{position}")
            } else {
                c_syntax::local_name(local.name)
            };
            let ty = self.types.name(&local.ty);
            if local.by_reference {
                parameters.push(format!("{ty} *{name}"));
                if Storage::of(&local.ty) == Storage::Text {
                    parameters.push(format!(
                        "lymra_data_stack *{}",
                        c_syntax::text_stack_name(&name)
                    ));
                    parameters.push(format!("char *{}", c_syntax::text_start_name(&name)));
                }
            } else if is_pointer(function, id) {
                parameters.push(format!("const {ty} *{name}"));
            } else {
                parameters.push(format!("const {ty} {name}"));
            }
        }
        let parameters = if parameters.is_empty() {
            "void".to_owned()
        } else {
            parameters.join(", ")
        };
        format!(
            "LYMRA_UNUSED static {return_type} {}({parameters})",
            c_syntax::function_name(function.name)
        )
    }

    /// Hands out a data stack of its own to a list or to text.
    fn new_data_stack(&mut self) -> usize {
        let stack = self.data_stacks;
        self.data_stacks += 1;
        stack
    }

    /**
     * Hands out the data stacks a value that keeps `storage` builds on, in
     * the order a function that returns it takes them. For text, it also
     * notes where the text will start, which freeing it moves the top back
     * to, and returns that note's name.
     */
    fn new_stacks(
        &mut self,
        storage: Storage,
        writer: &mut Writer,
    ) -> (Vec<usize>, Option<String>) {
        let count = destination_names(storage).len();
        let stacks: Vec<usize> = (0..count).map(|_| self.new_data_stack()).collect();
        if storage != Storage::Text {
            return (stacks, None);
        }
        let start = self.helper("text_start");
        writer.line(&format!(
            "char *const {start} = ({})->top;",
            data_stack(stacks[0])
        ));
        (stacks, Some(start))
    }

    /// Frees what `releases` hold, which come oldest first, the newest first.
    fn release(writer: &mut Writer, releases: &[Release]) {
        for release in releases.iter().rev() {
            writer.line(&format!(
                "lymra_data_stack_release({}, {});",
                data_stack(release.stack),
                release.start
            ));
        }
    }

    /// The lists open where control is now, oldest first: each open block's, then the statement's own.
    fn open_lists(&self) -> Vec<Release> {
        self.scopes
            .iter()
            .flat_map(|scope| scope.releases.iter())
            .chain(&self.pending)
            .cloned()
            .collect()
    }

    /// The lists `break` or `continue` frees, oldest first: those of the innermost loop's body and the blocks inside it.
    fn loop_lists(&self) -> Vec<Release> {
        let body = self
            .scopes
            .iter()
            .rposition(|scope| scope.loop_body)
            .unwrap_or(0);
        self.scopes[body..]
            .iter()
            .flat_map(|scope| scope.releases.iter())
            .cloned()
            .collect()
    }

    fn constants(&mut self) -> Vec<String> {
        self.program
            .constants
            .iter()
            // A constant named `_` can never be read, so it needs no storage.
            .filter(|constant| constant.name != "_")
            .map(|constant| {
                format!(
                    "LYMRA_UNUSED static const {} {} = {};",
                    self.types.name(&constant.value.ty()),
                    c_syntax::constant_name(constant.name),
                    c_syntax::static_initializer(&constant.value)
                )
            })
            .collect()
    }

    /// Registers a place that can stop the program and returns the name of its description.
    fn site(&mut self, span: Span) -> String {
        let name = format!("lymra_site_{}", self.sites.len());
        let description = render_location(span, self.source);
        self.sites.push(format!(
            "static const char {name}[] = {};",
            c_syntax::string_literal(&description)
        ));
        name
    }

    /// A new name for a helper variable, made of `role` and a number no other helper has.
    fn helper(&mut self, role: &str) -> String {
        let name = format!("{role}_{}", self.helpers);
        self.helpers += 1;
        name
    }
}

/// The name of the parameter that says on which data stack a function builds the list or the text it returns.
const DESTINATION: &str = "lymra_destination";

/// The name of the parameter that says on which data stack a function builds the text of the list it returns.
const DESTINATION_TEXT: &str = "lymra_destination_text";

/**
 * What freeing a value that keeps `storage` on `stacks` frees: the elements
 * of the list called `name`, its text, or text that starts at `text_start`.
 */
fn releases_of(
    storage: Storage,
    stacks: &[usize],
    name: &str,
    text_start: Option<String>,
) -> Vec<Release> {
    match (storage, stacks) {
        (Storage::Elements, &[elements]) => vec![Release::elements(elements, name)],
        (Storage::Text, &[text]) => text_start
            .map(|start| Release { stack: text, start })
            .into_iter()
            .collect(),
        (Storage::ElementsAndText, &[elements, text]) => vec![
            Release::elements(elements, name),
            Release {
                stack: text,
                start: format!("{name}.text"),
            },
        ],
        _ => Vec::new(),
    }
}

/// The parameters a function takes first, which say where to build a value it returns that keeps `storage` on data stacks.
fn destination_names(storage: Storage) -> Vec<&'static str> {
    match storage {
        Storage::None => Vec::new(),
        Storage::Elements | Storage::Text => vec![DESTINATION],
        Storage::ElementsAndText => vec![DESTINATION, DESTINATION_TEXT],
    }
}

/// The C for the address of data stack number `stack`.
fn data_stack(stack: usize) -> String {
    format!("&lymra_data_stacks[{stack}]")
}

/// The bytes a value of `ty` takes in a frame if it holds other values. Other values are too small to count.
fn compound_bytes(ty: &Type) -> u64 {
    if ty.is_compound() {
        ty.size().unwrap_or(u64::MAX)
    } else {
        0
    }
}

/**
 * Whether a local is reached through a pointer: a `variable` parameter, or a
 * parameter that holds other values, which is passed by address so no call
 * copies it.
 */
fn is_pointer(function: &Function<'_>, id: LocalId) -> bool {
    let local = &function.locals[id];
    local.by_reference || (local.ty.is_compound() && function.parameters.contains(&id))
}

/// The address of a local: its pointer when it has one.
fn local_address(function: &Function<'_>, id: LocalId) -> String {
    let name = c_syntax::local_name(function.locals[id].name);
    if is_pointer(function, id) {
        name
    } else {
        format!("&{name}")
    }
}

/// How a local is read or assigned: through its pointer when it has one.
fn local_access(function: &Function<'_>, id: LocalId) -> String {
    let name = c_syntax::local_name(function.locals[id].name);
    if is_pointer(function, id) {
        format!("(*{name})")
    } else {
        name
    }
}
